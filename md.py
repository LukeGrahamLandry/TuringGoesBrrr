import os, markdown, sys

template_html = """
<!DOCTYPE html>
<html lang="en">
<head>
    <style>
        body {
            text-align: center;
        }

        div {
            width: 100%;
            max-width: 800px;
            display: inline-block;
            text-align: left;
        }

        a {
            color: #0366d6;
            text-decoration: none;
        }

        .markdown-body {
            color: rgb(37, 41, 47);
            font-size: 16px;
            font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Helvetica, Arial, sans-serif, "Apple Color Emoji", "Segoe UI Emoji";
            line-height: 1.5;
        }

        .markdown-body pre {
            background-color: rgb(247, 248, 250);
            padding-left: 15px;
            padding-right: 15px;
            line-height: 1;
        }

        .markdown-body code {
            padding: 0.2em 0.4em;
            font-size: 85%;
            background-color: rgb(247, 248, 250);
            font-family: ui-monospace, SFMono-Regular, "SF Mono", Menlo, Consolas, "Liberation Mono", monospace;
        }

        .markdown-body h2, .markdown-body h1 {
            border-bottom: 1px solid rgb(217, 222, 228);
        }

        .markdown-body ul, .markdown-body ol {
            line-height: 1;
        }
    </style>
</head>
<body>
    <!-- Generated by TuringGoesBrrr:md.py -->
    <a href="/"> TuringGoesBrrr </a> <br>
    <div class="markdown-body">
        $CONTENT
    </div>
    <br> 
    <a href="/"> TuringGoesBrrr </a> <br> <br>
</body>
</html>
"""

def compileMD(from_file, to_file):
    with open(from_file, "r") as f:
        md_content = "\n".join(f.readlines())

    html_content = markdown.markdown(md_content, extensions=['fenced_code', 'tables'])
    full_content = template_html.replace("$CONTENT", html_content)

    with open(to_file, "w") as f:
        f.write(full_content)

    return html_content

def compileDirectory(input_dir, output_dir):
    base_root = None 
    for root, dirs, files in os.walk(input_dir, topdown=True):
        if base_root is None:
            base_root = root

        directory = root.replace(base_root, "")

        for dir in dirs:
            path = output_dir + directory + "/" + dir
            if (not os.path.exists(path)):
                os.mkdir(path)

        for filename in files:
            if filename.split(".")[-1] != "md":
                continue

            if len(directory) > 0 and directory[0] == "/":
                directory = directory[1:]

            out_filename = ".".join(filename.split(".")[:-1]) + ".html"
            path = output_dir + directory + "/" + out_filename

            compileMD(root + "/" + filename, path)

if __name__ == "__main__":
    compileDirectory(sys.argv[1], sys.argv[2])
    if len(sys.argv) > 3 and sys.argv[3].lower() == "true":
        compileMD("README.md", sys.argv[2] + "readme.html")

import os, markdown, sys

config = {}
template_html = \
"""
<!DOCTYPE html>
<html lang="en">
<head>
    <link rel="stylesheet" href="/style/md.css">
    <title> $TITLE </title>
    <link rel="canonical" href="$PATH">
</head>
<body>
    <a href="/"> Home </a> <br>
    <!-- generated by https://github.com/LukeGrahamLandry/TuringGoesBrrr/blob/main/scripts/md.py -->
    <div class="markdown-body">
        $CONTENT
    </div>
    <br> 
    <div class="menu">
        <a href="/"> Home </a>
    </div>
</body>
</html>
"""

def compileMD(from_file, to_file):
    print("generating ", to_file)
    with open(from_file, "r") as f:
        md_content = "\n".join(f.readlines())

    html_content = markdown.markdown(md_content, extensions=['fenced_code', 'tables'])
    full_content = template_html.replace("$CONTENT", html_content) \
                                .replace("$TITLE", "") \
                                .replace("$PATH", config["url_prefix"] + to_file.replace("dist/", "/").replace(".html", ""))

    with open(to_file, "w") as f:
        f.write(full_content)

    return html_content

def compileDirectory(input_dir, output_dir):
    base_root = None 
    for root, dirs, files in os.walk(input_dir, topdown=True):
        if base_root is None:
            base_root = root

        directory = root.replace(base_root, "")

        for dir in dirs:
            path = output_dir + directory + "/" + dir
            if (not os.path.exists(path)):
                os.mkdir(path)

        for filename in files:
            if filename.split(".")[-1] != "md":
                continue

            if len(directory) > 0 and directory[0] == "/":
                directory = directory[1:]

            out_filename = ".".join(filename.split(".")[:-1]) + ".html"
            path = output_dir + directory + "/" + out_filename
            path = path.replace("//", "/")

            compileMD(root + "/" + filename, path)

if __name__ == "__main__":
    config["in_dir"] = sys.argv[1]
    config["out_dir"] = sys.argv[2] + "/"
    config["url_prefix"] = sys.argv[3]
    config["include_readme"] = len(sys.argv) > 4 and sys.argv[4].lower() == "true"

    compileDirectory(config["in_dir"], config["out_dir"])
    if config["include_readme"]:
        compileMD("README.md", config["out_dir"] + "readme.html")
